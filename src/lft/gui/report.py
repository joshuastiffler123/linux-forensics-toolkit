def generate_html_report(
    output_dir: str | None,
    results: List[Dict],
    version: str,
    parent=None,
) -> str | None:
    """Generate and save an HTML analysis report.

    Opens a file-save dialog, writes the report, and optionally opens it
    in the default browser.  Returns the saved path, or None if cancelled.
    """
    path = filedialog.asksaveasfilename(
        parent=parent,
        title="Export HTML Report",
        defaultextension=".html",
        initialfile="lft_report.html",
        initialdir=output_dir or ".",
    )
    if not path:
        return None

    html_content = _render_html(results, version, output_dir)

    with open(path, "w", encoding="utf-8") as f:
        f.write(html_content)

    # Offer to open in browser
    try:
        webbrowser.open(f"file://{os.path.abspath(path)}")
    except Exception:
        pass

    return path


def export_csv_summary(
    output_dir: str | None,
    results: List[Dict],
    parent=None,
) -> str | None:
    """Export a single CSV summarising all analyzer results.

    Returns the saved path, or None if cancelled.
    """
    path = filedialog.asksaveasfilename(
        parent=parent,
        title="Export CSV Summary",
        defaultextension=".csv",
        initialfile="lft_summary.csv",
        initialdir=output_dir or ".",
    )
    if not path:
        return None

    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["Analyzer", "Status", "Events", "Findings", "Files", "Error"])
        for r in results:
            if not isinstance(r, dict):
                continue
            writer.writerow([
                r.get("name", "?"),
                "OK" if r.get("success") else "FAIL",
                r.get("event_count", 0) or 0,
                r.get("finding_count", 0) or 0,
                len(r.get("output_files", [])),
                r.get("error", ""),
            ])

    return path


