def _render_html(results: List[Dict], version: str, output_dir: str | None) -> str:
    """Build the full HTML string."""
    results = [r for r in results if isinstance(r, dict)]

    passed = sum(1 for r in results if r.get("success"))
    failed = len(results) - passed
    total_events = sum(r.get("event_count", 0) or 0 for r in results)
    total_findings = sum(r.get("finding_count", 0) or 0 for r in results)

    # Summary rows
    summary_lines = []
    for r in results:
        ok = r.get("success", False)
        cls = "ok" if ok else "fail"
        status = "OK" if ok else "FAIL"
        summary_lines.append(
            f'    <tr>'
            f'<td>{html.escape(r.get("name", "?"))}</td>'
            f'<td class="{cls}">{status}</td>'
            f'<td>{r.get("event_count", 0) or 0:,}</td>'
            f'<td>{r.get("finding_count", 0) or 0:,}</td>'
            f'<td>{len(r.get("output_files", []))}</td>'
            f'</tr>'
        )

    # Per-analyzer detail sections with CSV preview
    detail_parts = []
    for r in results:
        name = html.escape(r.get("name", "?"))
        csv_files = r.get("output_files", [])
        if not csv_files:
            continue

        section = f'<div class="section">\n<h2>{name}</h2>\n'

        for csv_path in csv_files[:3]:  # max 3 files per analyzer
            if not os.path.isfile(csv_path):
                continue
            basename = html.escape(os.path.basename(csv_path))
            section += f'<h3>{basename}</h3>\n'
            section += _csv_to_html_table(csv_path, max_rows=20)

        section += "</div>\n"
        detail_parts.append(section)

    return _HTML_TEMPLATE.format(
        version=html.escape(version),
        timestamp=html.escape(datetime.now().strftime("%Y-%m-%d %H:%M:%S")),
        total_analyzers=len(results),
        passed=passed,
        failed=failed,
        total_events=total_events,
        total_findings=total_findings,
        summary_rows="\n".join(summary_lines),
        detail_sections="\n".join(detail_parts),
    )


def _csv_to_html_table(csv_path: str, max_rows: int = 20) -> str:
    """Read a CSV file and return an HTML table string."""
    try:
        size = os.path.getsize(csv_path)
        if size > 2_000_000:  # 2 MB safety limit
            return "<p><em>File too large for inline preview.</em></p>\n"

        with open(csv_path, "r", newline="", errors="replace") as f:
            reader = csv.reader(f)
            headers = next(reader, None)
            if not headers:
                return "<p><em>Empty CSV.</em></p>\n"

            # Cap columns at 10
            max_cols = 10
            truncated_cols = len(headers) > max_cols
            headers = headers[:max_cols]

            parts = ["<table>\n<thead><tr>"]
            for h in headers:
                parts.append(f"<th>{html.escape(h[:80])}</th>")
            if truncated_cols:
                parts.append("<th>...</th>")
            parts.append("</tr></thead>\n<tbody>\n")

            count = 0
            for row in reader:
                if count >= max_rows:
                    break
                parts.append("<tr>")
                for cell in row[:max_cols]:
                    val = cell[:80] if len(cell) > 80 else cell
                    parts.append(f"<td>{html.escape(val)}</td>")
                if truncated_cols:
                    parts.append("<td>...</td>")
                parts.append("</tr>\n")
                count += 1

            parts.append("</tbody></table>\n")

            if count >= max_rows:
                parts.append(
                    f"<p><em>Showing first {max_rows} rows.</em></p>\n"
                )

            return "".join(parts)

    except Exception:
        return "<p><em>Could not read CSV file.</em></p>\n"
